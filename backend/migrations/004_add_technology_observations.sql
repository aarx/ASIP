BEGIN;

CREATE TABLE public.domain_technology_observations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id integer NOT NULL,
    domain_id integer NOT NULL,
    technology text NOT NULL,
    version text,
    confidence text NOT NULL,
    evidence_type text NOT NULL,
    sanitized_evidence text NOT NULL,
    observed_url text,
    detector_version text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT domain_technology_observations_confidence_check
        CHECK (confidence IN ('high', 'medium', 'low', 'none')),
    CONSTRAINT domain_technology_observations_technology_check
        CHECK (btrim(technology) <> ''),
    CONSTRAINT domain_technology_observations_evidence_type_check
        CHECK (btrim(evidence_type) <> ''),
    CONSTRAINT domain_technology_observations_evidence_check
        CHECK (btrim(sanitized_evidence) <> ''),
    CONSTRAINT domain_technology_observations_detector_check
        CHECK (btrim(detector_version) <> ''),
    CONSTRAINT domain_technology_observations_scan_domain_fkey
        FOREIGN KEY (scan_id, domain_id)
        REFERENCES public.scan_results (scan_id, domain_id),
    CONSTRAINT domain_technology_observations_scan_fkey
        FOREIGN KEY (scan_id)
        REFERENCES public.scans (id),
    CONSTRAINT domain_technology_observations_domain_fkey
        FOREIGN KEY (domain_id)
        REFERENCES public.domains (id)
);

CREATE INDEX idx_domain_technology_observations_domain_scan
    ON public.domain_technology_observations (domain_id, scan_id);

CREATE UNIQUE INDEX uq_domain_technology_observations_identity
    ON public.domain_technology_observations (
        scan_id,
        domain_id,
        technology,
        COALESCE(version, ''),
        evidence_type,
        sanitized_evidence,
        COALESCE(observed_url, ''),
        detector_version
    );

COMMIT;
