BEGIN;

CREATE TABLE public.capd_runs (
    run_id uuid PRIMARY KEY,
    check_id text NOT NULL,
    check_revision text NOT NULL,
    cve_id text NOT NULL,
    check_definition jsonb NOT NULL CHECK (jsonb_typeof(check_definition) = 'object'),
    source_scan_id integer NOT NULL REFERENCES public.scans(id),
    execution_mode text NOT NULL CHECK (execution_mode = 'PASSIVE'),
    status text NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamptz,
    target_limit integer NOT NULL CHECK (target_limit BETWEEN 1 AND 1000),
    eligible_target_count integer NOT NULL DEFAULT 0 CHECK (eligible_target_count >= 0),
    selected_target_count integer NOT NULL DEFAULT 0 CHECK (selected_target_count >= 0),
    skipped_target_count integer NOT NULL DEFAULT 0 CHECK (skipped_target_count >= 0),
    selection_summary jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(selection_summary) = 'object'),
    counts jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(counts) = 'object'),
    error_code text,
    CONSTRAINT capd_runs_check_revision_nonempty CHECK (btrim(check_revision) <> ''),
    CONSTRAINT capd_runs_check_id_nonempty CHECK (btrim(check_id) <> '')
);

CREATE INDEX idx_capd_runs_created ON public.capd_runs (started_at DESC, run_id DESC);
CREATE INDEX idx_capd_runs_check ON public.capd_runs (check_id, started_at DESC);

CREATE TABLE public.capd_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id uuid NOT NULL REFERENCES public.capd_runs(run_id) ON DELETE CASCADE,
    domain_id integer NOT NULL REFERENCES public.domains(id),
    domain_snapshot text NOT NULL,
    asset_class_snapshot text NOT NULL CHECK (asset_class_snapshot IN ('KNOWN', 'SHADOW')),
    evidence_identity text NOT NULL,
    result_status text NOT NULL CHECK (result_status IN (
        'POTENTIAL_MATCH', 'INSUFFICIENT_EVIDENCE', 'NOT_APPLICABLE', 'UNSUPPORTED', 'ERROR'
    )),
    candidate_classification text NOT NULL CHECK (candidate_classification IN (
        'VERSION_MATCHED', 'PRODUCT_MATCHED_VERSION_UNKNOWN', 'SERVICE_CANDIDATE',
        'NOT_APPLICABLE', 'INSUFFICIENT_EVIDENCE'
    )),
    product text,
    version text,
    detection_confidence text,
    match_confidence text,
    evidence jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(evidence) = 'array'),
    explanation text NOT NULL,
    limitations jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(limitations) = 'array'),
    assessed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT capd_results_evidence_identity_nonempty CHECK (btrim(evidence_identity) <> ''),
    CONSTRAINT capd_results_run_asset_evidence_unique UNIQUE (run_id, domain_id, evidence_identity)
);

CREATE INDEX idx_capd_results_run_status ON public.capd_results (run_id, result_status, id);
CREATE INDEX idx_capd_results_domain ON public.capd_results (domain_id, assessed_at DESC);

COMMIT;
