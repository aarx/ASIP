BEGIN;

CREATE TABLE public.adhoc_campaigns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id text NOT NULL,
    source_scan_id integer NOT NULL,
    requested_by text NOT NULL,
    idempotency_key text NOT NULL,
    target_set jsonb NOT NULL,
    request_fingerprint text NOT NULL,
    assessment_date date NOT NULL,
    dataset_revision text NOT NULL,
    status text NOT NULL DEFAULT 'QUEUED',
    failure_code text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at timestamptz,
    completed_at timestamptz,
    cancel_requested_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT adhoc_campaigns_check_id_check
        CHECK (btrim(check_id) <> ''),
    CONSTRAINT adhoc_campaigns_requested_by_check
        CHECK (btrim(requested_by) <> ''),
    CONSTRAINT adhoc_campaigns_idempotency_key_check
        CHECK (btrim(idempotency_key) <> ''),
    CONSTRAINT adhoc_campaigns_target_set_check
        CHECK (jsonb_typeof(target_set) = 'array' AND jsonb_array_length(target_set) > 0),
    CONSTRAINT adhoc_campaigns_request_fingerprint_check
        CHECK (btrim(request_fingerprint) <> ''),
    CONSTRAINT adhoc_campaigns_status_check
        CHECK (status IN (
            'QUEUED', 'RUNNING', 'CANCEL_REQUESTED', 'CANCELLED',
            'SUCCEEDED', 'PARTIAL', 'FAILED'
        )),
    CONSTRAINT adhoc_campaigns_id_source_scan_key
        UNIQUE (id, source_scan_id),
    CONSTRAINT adhoc_campaigns_source_scan_fkey
        FOREIGN KEY (source_scan_id)
        REFERENCES public.scans (id)
);

CREATE UNIQUE INDEX uq_adhoc_campaigns_idempotency
    ON public.adhoc_campaigns (idempotency_key);

CREATE INDEX idx_adhoc_campaigns_status_created
    ON public.adhoc_campaigns (status, created_at DESC);

CREATE INDEX idx_adhoc_campaigns_check_scan
    ON public.adhoc_campaigns (check_id, source_scan_id, created_at DESC);

CREATE TABLE public.adhoc_campaign_targets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint NOT NULL,
    source_scan_id integer NOT NULL,
    domain_id integer NOT NULL,
    domain_snapshot text NOT NULL,
    ownership_status_snapshot text NOT NULL,
    scannable_snapshot boolean NOT NULL,
    validation_source_snapshot text,
    target_status text NOT NULL DEFAULT 'PENDING',
    skip_reason_code text,
    selected_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at timestamptz,
    completed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT adhoc_campaign_targets_campaign_fkey
        FOREIGN KEY (campaign_id)
        REFERENCES public.adhoc_campaigns (id),
    CONSTRAINT adhoc_campaign_targets_campaign_scan_fkey
        FOREIGN KEY (campaign_id, source_scan_id)
        REFERENCES public.adhoc_campaigns (id, source_scan_id),
    CONSTRAINT adhoc_campaign_targets_campaign_id_key
        UNIQUE (campaign_id, id),
    CONSTRAINT adhoc_campaign_targets_scan_domain_fkey
        FOREIGN KEY (source_scan_id, domain_id)
        REFERENCES public.scan_results (scan_id, domain_id),
    CONSTRAINT adhoc_campaign_targets_domain_fkey
        FOREIGN KEY (domain_id)
        REFERENCES public.domains (id),
    CONSTRAINT adhoc_campaign_targets_domain_check
        CHECK (btrim(domain_snapshot) <> ''),
    CONSTRAINT adhoc_campaign_targets_status_check
        CHECK (target_status IN (
            'PENDING', 'RUNNING', 'COMPLETED', 'SKIPPED',
            'FAILED', 'CANCELLED'
        )),
    CONSTRAINT adhoc_campaign_targets_snapshot_status_check
        CHECK (ownership_status_snapshot IN ('CONFIRMED', 'CANDIDATE', 'EXTERNAL')),
    CONSTRAINT adhoc_campaign_targets_scope_unique
        UNIQUE (campaign_id, domain_id)
);

CREATE INDEX idx_adhoc_campaign_targets_campaign_status
    ON public.adhoc_campaign_targets (campaign_id, target_status, id);

CREATE INDEX idx_adhoc_campaign_targets_scan_domain
    ON public.adhoc_campaign_targets (source_scan_id, domain_id);

CREATE TABLE public.adhoc_campaign_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint NOT NULL,
    target_id bigint NOT NULL,
    attempt_number integer NOT NULL DEFAULT 1,
    execution_status text NOT NULL,
    evidence_status text NOT NULL DEFAULT 'NOT_COLLECTED',
    evaluation_status text NOT NULL DEFAULT 'NOT_EVALUATED',
    classification text,
    failure_code text,
    skip_reason_code text,
    observations jsonb NOT NULL DEFAULT '[]'::jsonb,
    lifecycle jsonb,
    cve_intelligence jsonb,
    observed_at timestamptz,
    persisted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dataset_revision text,
    CONSTRAINT adhoc_campaign_results_campaign_fkey
        FOREIGN KEY (campaign_id)
        REFERENCES public.adhoc_campaigns (id),
    CONSTRAINT adhoc_campaign_results_target_fkey
        FOREIGN KEY (campaign_id, target_id)
        REFERENCES public.adhoc_campaign_targets (campaign_id, id),
    CONSTRAINT adhoc_campaign_results_attempt_check
        CHECK (attempt_number > 0),
    CONSTRAINT adhoc_campaign_results_execution_check
        CHECK (execution_status IN (
            'PENDING', 'RUNNING', 'COMPLETED', 'SKIPPED',
            'FAILED', 'CANCELLED'
        )),
    CONSTRAINT adhoc_campaign_results_evidence_check
        CHECK (evidence_status IN (
            'NOT_COLLECTED', 'COLLECTED', 'FAILED', 'BLOCKED'
        )),
    CONSTRAINT adhoc_campaign_results_evaluation_check
        CHECK (evaluation_status IN (
            'EVALUATED', 'NOT_EVALUATED', 'UNKNOWN'
        )),
    CONSTRAINT adhoc_campaign_results_observations_check
        CHECK (jsonb_typeof(observations) = 'array'),
    CONSTRAINT adhoc_campaign_results_attempt_unique
        UNIQUE (campaign_id, target_id, attempt_number)
);

CREATE INDEX idx_adhoc_campaign_results_campaign_status
    ON public.adhoc_campaign_results (campaign_id, execution_status, id);

CREATE INDEX idx_adhoc_campaign_results_classification
    ON public.adhoc_campaign_results (campaign_id, classification);

COMMIT;
