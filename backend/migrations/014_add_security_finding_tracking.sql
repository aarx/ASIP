BEGIN;

CREATE TABLE public.tracked_security_issues (
    issue_id text PRIMARY KEY,
    domain_id integer NOT NULL REFERENCES public.domains (id),
    asset_domain_snapshot text NOT NULL,
    asset_class_snapshot text NOT NULL,
    source text NOT NULL,
    finding_type text NOT NULL,
    identity_discriminator text NOT NULL,
    finding_category text NOT NULL,
    source_record_id text NOT NULL,
    source_outcome text,
    source_confidence text,
    source_severity text,
    first_observed_at timestamptz NOT NULL,
    last_observed_at timestamptz NOT NULL,
    first_observed_scan_id integer NOT NULL REFERENCES public.scans (id),
    last_observed_scan_id integer NOT NULL REFERENCES public.scans (id),
    analyst_status text NOT NULL DEFAULT 'OPEN',
    created_by text NOT NULL,
    status_changed_by text NOT NULL,
    status_changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tracked_security_issues_issue_id_check
        CHECK (issue_id ~ '^sfi:v1:[0-9a-f]{64}$'),
    CONSTRAINT tracked_security_issues_source_check
        CHECK (btrim(source) <> '' AND length(source) <= 128),
    CONSTRAINT tracked_security_issues_type_check
        CHECK (btrim(finding_type) <> '' AND length(finding_type) <= 256),
    CONSTRAINT tracked_security_issues_discriminator_check
        CHECK (btrim(identity_discriminator) <> '' AND length(identity_discriminator) <= 1024),
    CONSTRAINT tracked_security_issues_domain_snapshot_check
        CHECK (btrim(asset_domain_snapshot) <> ''),
    CONSTRAINT tracked_security_issues_class_snapshot_check
        CHECK (asset_class_snapshot IN ('KNOWN', 'SHADOW')),
    CONSTRAINT tracked_security_issues_category_check
        CHECK (finding_category IN ('FINDING', 'NEEDS_VERIFICATION')),
    CONSTRAINT tracked_security_issues_status_check
        CHECK (analyst_status IN (
            'OPEN', 'IN_REVIEW', 'REMEDIATED', 'FALSE_POSITIVE', 'RISK_ACCEPTED'
        )),
    CONSTRAINT tracked_security_issues_observation_order_check
        CHECK (last_observed_at >= first_observed_at),
    CONSTRAINT tracked_security_issues_actor_check
        CHECK (btrim(created_by) <> '' AND btrim(status_changed_by) <> ''),
    CONSTRAINT tracked_security_issues_source_record_check
        CHECK (btrim(source_record_id) <> '' AND length(source_record_id) <= 512),
    CONSTRAINT tracked_security_issues_identity_unique
        UNIQUE (domain_id, source, finding_type, identity_discriminator)
);

CREATE INDEX idx_tracked_security_issues_status_updated
    ON public.tracked_security_issues (analyst_status, updated_at DESC, issue_id);
CREATE INDEX idx_tracked_security_issues_domain
    ON public.tracked_security_issues (domain_id, updated_at DESC);

CREATE TABLE public.tracked_security_issue_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id text NOT NULL REFERENCES public.tracked_security_issues (issue_id),
    event_type text NOT NULL,
    previous_status text,
    new_status text NOT NULL,
    actor_identity text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason text,
    evidence_scan_id integer REFERENCES public.scans (id),
    source_record_id text,
    CONSTRAINT tracked_security_issue_history_event_check
        CHECK (event_type IN (
            'TRACKING_STARTED', 'STATUS_CHANGED', 'REOPENED', 'REOBSERVED'
        )),
    CONSTRAINT tracked_security_issue_history_event_shape_check
        CHECK (
            (event_type = 'TRACKING_STARTED' AND previous_status IS NULL AND new_status = 'OPEN')
            OR (event_type = 'REOPENED' AND previous_status IS NOT NULL
                AND previous_status IN ('REMEDIATED', 'FALSE_POSITIVE', 'RISK_ACCEPTED')
                AND new_status = 'OPEN')
            OR (event_type = 'STATUS_CHANGED' AND previous_status IS NOT NULL
                AND previous_status <> new_status)
            OR (event_type = 'REOBSERVED' AND previous_status IS NOT NULL
                AND previous_status = new_status)
        ),
    CONSTRAINT tracked_security_issue_history_previous_check
        CHECK (previous_status IS NULL OR previous_status IN (
            'OPEN', 'IN_REVIEW', 'REMEDIATED', 'FALSE_POSITIVE', 'RISK_ACCEPTED'
        )),
    CONSTRAINT tracked_security_issue_history_new_check
        CHECK (new_status IN (
            'OPEN', 'IN_REVIEW', 'REMEDIATED', 'FALSE_POSITIVE', 'RISK_ACCEPTED'
        )),
    CONSTRAINT tracked_security_issue_history_actor_check
        CHECK (btrim(actor_identity) <> ''),
    CONSTRAINT tracked_security_issue_history_reason_check
        CHECK (reason IS NULL OR length(reason) <= 2000),
    CONSTRAINT tracked_security_issue_history_source_record_check
        CHECK (source_record_id IS NULL OR length(source_record_id) <= 512)
);

CREATE INDEX idx_tracked_security_issue_history_issue_time
    ON public.tracked_security_issue_history (issue_id, occurred_at, id);

CREATE FUNCTION public.reject_tracked_security_issue_history_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'tracked security issue history is append-only';
END;
$$;

CREATE TRIGGER tracked_security_issue_history_append_only
    BEFORE UPDATE OR DELETE ON public.tracked_security_issue_history
    FOR EACH ROW
    EXECUTE FUNCTION public.reject_tracked_security_issue_history_mutation();

COMMIT;
