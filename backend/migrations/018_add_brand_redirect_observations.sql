BEGIN;

CREATE TABLE public.brand_redirect_observations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id integer NOT NULL,
    domain_id integer NOT NULL,
    operation_id uuid NOT NULL,
    observed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    evidence_source text NOT NULL
        CHECK (evidence_source = 'BRAND_REDIRECT_INTELLIGENCE'),
    completeness text NOT NULL CHECK (completeness IN (
        'COMPLETE', 'NO_REDIRECT', 'STOPPED_AT_AUTHORIZATION_BOUNDARY',
        'TIMEOUT', 'ERROR', 'REDIRECT_LOOP', 'MAX_REDIRECT_HOPS'
    )),
    evidence jsonb NOT NULL CHECK (jsonb_typeof(evidence) = 'object'),
    CONSTRAINT brand_redirect_observations_scan_domain_fkey
        FOREIGN KEY (scan_id, domain_id)
        REFERENCES public.scan_results (scan_id, domain_id),
    CONSTRAINT brand_redirect_observations_scan_fkey
        FOREIGN KEY (scan_id) REFERENCES public.scans (id),
    CONSTRAINT brand_redirect_observations_domain_fkey
        FOREIGN KEY (domain_id) REFERENCES public.domains (id)
);

CREATE INDEX idx_brand_redirect_observations_domain_time
    ON public.brand_redirect_observations (domain_id, observed_at DESC, id DESC);

CREATE INDEX idx_brand_redirect_observations_scan_domain
    ON public.brand_redirect_observations (scan_id, domain_id, observed_at DESC);

CREATE UNIQUE INDEX uq_brand_redirect_observations_operation_domain
    ON public.brand_redirect_observations (operation_id, domain_id);

COMMIT;
